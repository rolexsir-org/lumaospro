package com.rolexm.launcher.robolectric

import androidx.test.core.app.ApplicationProvider
import com.rolexm.launcher.core.RolexApp
import com.rolexm.launcher.diagnostics.DiagnosticsStore
import com.rolexm.launcher.diagnostics.OptimizationEvent
import com.rolexm.launcher.diagnostics.StartupStats
import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Before
import org.junit.Test
import org.junit.runner.RunWith
import org.robolectric.RobolectricTestRunner
import org.robolectric.annotation.Config

/**
 * Exercises the hand-written SQL against a real SQLite database.
 *
 * The SQL in DiagnosticsStore is not generated by Room, so no compiler checks
 * it: a typo in a column name or an inverted ORDER BY would only ever surface
 * at runtime. These tests run it for real.
 */
@RunWith(RobolectricTestRunner::class)
@Config(sdk = [34], application = RolexApp::class)
class DiagnosticsStoreRuntimeTest {

    private lateinit var store: DiagnosticsStore

    @Before
    fun setUp() {
        store = DiagnosticsStore(ApplicationProvider.getApplicationContext())
        store.clearHistory()
    }

    private fun event(
        id: Long = 0L,
        ts: Long = 1_000L,
        actionId: String = "trim_icon_cache",
        title: String = "Trim icon cache",
        trigger: String = "manual",
        completed: Boolean = true,
        detail: String = "did a thing",
        durationMs: Long = 42L,
        beforeKb: Int? = 40_000,
        afterKb: Int? = 38_000,
        freed: Long = 0L,
        improved: Boolean = true
    ) = OptimizationEvent(id, ts, actionId, title, trigger, completed, detail, durationMs, beforeKb, afterKb, freed, improved)

    @Test
    fun `an event round trips through SQLite with every field intact`() {
        val inserted = store.insertEvent(event(ts = 1_234L))
        assertTrue("insert should return a row id", inserted > 0L)

        val read = store.recentEvents(10).single()
        assertEquals(1_234L, read.timestampMillis)
        assertEquals("trim_icon_cache", read.actionId)
        assertEquals("Trim icon cache", read.actionTitle)
        assertEquals("manual", read.trigger)
        assertEquals(true, read.completed)
        assertEquals("did a thing", read.detail)
        assertEquals(42L, read.durationMs)
        assertEquals(40_000, read.beforePssKb)
        assertEquals(38_000, read.afterPssKb)
        assertEquals(-2_000, read.pssDeltaKb) // 38_000 - 40_000
        assertEquals(true, read.measuredImprovement)
    }

    @Test
    fun `null pss readings survive as null rather than becoming zero`() {
        store.insertEvent(event(beforeKb = null, afterKb = null))
        val read = store.recentEvents(1).single()
        assertEquals(null, read.beforePssKb)
        assertEquals(null, read.afterPssKb)
        assertEquals(null, read.pssDeltaKb)
    }

    @Test
    fun `history is capped so the database cannot grow without bound`() {
        repeat(DiagnosticsStore.MAX_EVENTS + 60) { index ->
            store.insertEvent(event(ts = index.toLong()))
        }
        val all = store.recentEvents(DiagnosticsStore.MAX_EVENTS)
        assertEquals(DiagnosticsStore.MAX_EVENTS, all.size)
        // The newest must be kept and the oldest dropped.
        assertEquals((DiagnosticsStore.MAX_EVENTS + 59).toLong(), all.first().timestampMillis)
        assertEquals(60L, all.last().timestampMillis)
    }

    @Test
    fun `startup samples are capped and returned oldest first`() {
        repeat(DiagnosticsStore.MAX_STARTUP_SAMPLES + 10) { index ->
            store.recordStartup(durationMs = 100L + index, atMillis = index.toLong())
        }
        val history = store.startupHistory(DiagnosticsStore.MAX_STARTUP_SAMPLES)
        assertEquals(DiagnosticsStore.MAX_STARTUP_SAMPLES, history.size)
        // Oldest first, so the dashboard can render a trend left to right.
        assertEquals(10L, history.first().first)
        assertEquals((DiagnosticsStore.MAX_STARTUP_SAMPLES + 9).toLong(), history.last().first)
        assertEquals(100L + 10, history.first().second)
    }

    @Test
    fun `startup statistics are derived from stored samples`() {
        store.recordStartup(400L, atMillis = 1L)
        store.recordStartup(200L, atMillis = 2L)
        store.recordStartup(300L, atMillis = 3L)

        val stats = StartupStats.from(store.startupHistory(10))!!
        assertEquals(3, stats.sampleCount)
        assertEquals(200L, stats.bestMs)
        assertEquals(300L, stats.medianMs)
        assertEquals(300L, stats.latestMs)
    }

    @Test
    fun `vacuum runs without error on a populated database`() {
        repeat(20) { store.insertEvent(event(ts = it.toLong())) }
        store.vacuum()
        assertEquals(20, store.recentEvents(50).size)
    }

    @Test
    fun `clearing history empties every table`() {
        store.insertEvent(event())
        store.recordStartup(100L)
        store.clearHistory()
        assertTrue(store.recentEvents(50).isEmpty())
        assertTrue(store.startupHistory(10).isEmpty())
    }

    @Test
    fun `the database reports a real file size once written`() {
        store.insertEvent(event())
        assertTrue("database file should have a non-zero size", store.databaseSizeBytes() > 0L)
    }
}
